export const AsciiArt = ({
  inverted = false,
  className,
  size = "md",
  color = "text-white/40",
}: AsciiArtProps) => {
  const sizePresets: Record<string, string> = {
    sm: "text-[2px] md:text-[2px]",
    md: "text-[4px] md:text-[4px]",
    lg: "text-[8px] md:text-[10px]",
  };

  const finalSize = sizePresets[size] || size;

  return (
    <pre
      className={cn(
        "font-mono leading-[1.1] tracking-[0.15em] select-none pointer-events-none text-center transition-all duration-300",
        finalSize,
        color,
        className
      )}
    >
      {inverted ? FLIPPED_ASCII : ORIGINAL_ASCII}
    </pre>
  );
};
